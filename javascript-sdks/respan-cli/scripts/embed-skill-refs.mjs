#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '../../..');
const SKILLS_DIR = resolve(REPO_ROOT, 'skills');
const OUT_FILE = resolve(__dirname, '../src/lib/skill-refs.generated.ts');

// The installed skill is a single SKILL.md, authored under skills/ and embedded
// here as a `*_MD` string constant. It links to the Respan docs for each task,
// so the setup steps and reference material live in the docs, not the skill.
const SOURCES = [
  { name: 'SKILL', file: resolve(SKILLS_DIR, 'SKILL.md') },
];

const escapeTemplate = (s) =>
  s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const lines = [
  '// AUTO-GENERATED by scripts/embed-skill-refs.mjs',
  '// Source: skills/SKILL.md',
  '// Do not edit directly — edit the markdown sources and rebuild.',
  '',
];

for (const { name, file } of SOURCES) {
  const content = readFileSync(file, 'utf8');
  const constName = `${name}_MD`;
  lines.push(`export const ${constName} = \`${escapeTemplate(content)}\`;`);
  lines.push('');
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT_FILE}`);
